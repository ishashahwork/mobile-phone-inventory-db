CREATE DATABASE PhoneAssignment;
USE PhoneAssignment ;

CREATE TABLE PERSON (
  PERSON_ID SMALLINT PRIMARY KEY AUTO_INCREMENT,
  FIRST_NAME VARCHAR(50) NOT NULL,
  LAST_NAME VARCHAR(50) NOT NULL,
  EMAIL VARCHAR(100) UNIQUE NOT NULL,
  BIRTH_DATE DATE
);
CREATE TABLE PHONE_COMPANY (
  COMPANY_ID SMALLINT PRIMARY KEY AUTO_INCREMENT,
  COMPANY_NAME VARCHAR(100) UNIQUE NOT NULL,
  HQ_COUNTRY VARCHAR(50),
  CUSTOMER_SUPPORT VARCHAR(20),
  WEBSITE_URL VARCHAR(150)
);
CREATE TABLE PHONE_MODEL (
  MODEL_ID SMALLINT AUTO_INCREMENT PRIMARY KEY,
  COMPANY_ID SMALLINT NOT NULL,
  MODEL_NAME VARCHAR(100) NOT NULL,
  RELEASE_YEAR SMALLINT,
  OPERATING_SYSTEM VARCHAR(50),
  STORAGE_CAPACITY_GB SMALLINT,
  FOREIGN KEY (COMPANY_ID) REFERENCES PHONE_COMPANY(COMPANY_ID) 
);
CREATE TABLE PERSON_PHONE (
  OWNERSHIP_ID SMALLINT PRIMARY KEY AUTO_INCREMENT,
  PERSON_ID SMALLINT NOT NULL,
  MODEL_ID SMALLINT NOT NULL,
  PURCHASE_DATE DATE,
  PHONE_NUMBER VARCHAR(20),
  IMEI_NUMBER VARCHAR(15) UNIQUE,
  FOREIGN KEY (PERSON_ID) REFERENCES PERSON(PERSON_ID), 
  FOREIGN KEY (MODEL_ID) REFERENCES PHONE_MODEL(MODEL_ID)
);
